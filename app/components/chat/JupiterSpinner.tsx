export function JupiterSpinner() {
  const [rotation, setRotation] = useState(0);

  useEffect(() => {
    const id = setInterval(() => {
      setRotation((r) => (r + 4) % 360);
    }, 60);
    return () => clearInterval(id);
  }, []);

  return (
    <div className="w-8 h-8 flex items-center justify-center overflow-hidden rounded-full">
      <pre
        className="font-mono text-[2px] leading-[2px] text-violet-500 select-none whitespace-pre"
        style={{
          transform: `scale(0.18) rotate(${rotation}deg)`,
          transformOrigin: "center",
        }}
      >
        {JUPITER_FRAMES}
      </pre>
    </div>
  );
}
